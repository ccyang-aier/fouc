function draft(provider: RelationalProvider, patch: Partial<TableCreateInput> = {}): TableCreateInput {
  return { schema: provider === 'sqlite' ? 'main' : 'lab', table: 'fresh', columns: [tableCreateNewColumn(provider, 'id', true)], ...patch };
}
function textColumn(provider: RelationalProvider, patch: Partial<TableCreateColumn> = {}): TableCreateColumn {
  return { ...tableCreateNewColumn(provider, 'label'), name: 'label', ...patch };
}
function result(rows: DriverResult['rows'], columns = ['name']): DriverResult { return { rows, columns, columnTypes: [], hasMore: false }; }
function fixture() {
  const state = { schemas: ['lab', 'main'], exists: false, permission: true, writes: [] as string[], fail: null as Error | null, after: null as (() => void) | null };
  const driver = {
    schemas: async () => state.schemas,
    read: async (sql: string) => sql.includes('has_schema_privilege') ? result([[state.permission]], ['allowed']) : result(state.exists ? [['existing']] : []),
    transaction: async (_schema: string, run: Parameters<RelationalDriver['transaction']>[1]) => {
      const value = await run({ query: async sql => {
        state.writes.push(sql); if (state.fail) throw state.fail;
        return { ...result([]), affectedRows: 0 };
      } });
      state.after?.(); return value;
    },
  } as unknown as RelationalDriver;
  return { driver, state };
}
const allowed = () => undefined;

test('native DDL retains exact literals, special identifiers and provider identity / composite key semantics', () => {
  const mysql = draft('mysql', { table: 'quote`table', columns: [tableCreateNewColumn('mysql', 'id', true), textColumn('mysql', { name: 'quote`column', nullable: false, unique: true, default: { kind: 'literal', value: "中文'\\path" } }), { ...textColumn('mysql'), id: 'decimal', name: 'amount', type: 'DECIMAL', length: null, precision: 40, scale: 18, default: { kind: 'literal', value: '9007199254740993.123456789012345678' } }] });
  const my = buildTableCreateReview('mysql', mysql).review;
  expect(my.sql).toContain('`quote``table`');
  expect(my.sql).toContain('`quote``column` VARCHAR(255) NOT NULL DEFAULT _utf8mb4 X\'e4b8ade69687275c70617468\' UNIQUE');
  expect(my.sql).toContain('DECIMAL(40,18) DEFAULT 9007199254740993.123456789012345678');
  expect(my.sql).toContain('AUTO_INCREMENT'); expect(my.sql).toEndWith('ENGINE=InnoDB;');
  expect(my.transaction).toBe('implicit-commit');
  const pg = buildTableCreateReview('postgres', draft('postgres', { table: '研究"table', columns: [tableCreateNewColumn('postgres', 'id', true), textColumn('postgres', { nullable: false, primaryKey: true, default: { kind: 'literal', value: "'); DROP TABLE public.secret; --\\" } })] })).review;
  expect(pg.sql).toContain('"研究""table"'); expect(pg.sql).toContain('GENERATED BY DEFAULT AS IDENTITY');
  expect(pg.sql).toContain("DEFAULT E'''); DROP TABLE public.secret; --\\\\'");
  expect(pg.sql).toContain('PRIMARY KEY ("id", "label")'); expect(pg.transaction).toBe('atomic');
});

test('strict design validation rejects SQL, incompatible lengths/defaults, duplicated names and invalid generated keys', () => {
  expect(() => validateTableCreateInput('postgres', { ...draft('postgres'), sql: 'DROP SCHEMA public' })).toThrow();
  const invalid: [RelationalProvider, TableCreateInput][] = [
    ['mysql', draft('mysql', { schema: 'mysql' })], ['sqlite', draft('sqlite', { schema: 'temp' })],
    ['postgres', draft('postgres', { table: '汉'.repeat(22) })],
    ['postgres', draft('postgres', { columns: [textColumn('postgres', { type: 'TEXT; DROP TABLE x' })] })],
    ['mysql', draft('mysql', { columns: [textColumn('mysql', { length: 0 })] })],
    ['postgres', draft('postgres', { columns: [textColumn('postgres', { default: { kind: 'function', value: 'pg_sleep(10)' } })] })],
    ['mysql', draft('mysql', { columns: [tableCreateNewColumn('mysql', 'id', true), textColumn('mysql', { id: 'label2', name: 'ID' })] })],
    ['sqlite', draft('sqlite', { columns: [tableCreateNewColumn('sqlite', 'id', true), textColumn('sqlite', { primaryKey: true, nullable: false })] })],
    ['postgres', draft('postgres', { columns: [{ ...tableCreateNewColumn('postgres', 'id', true), default: { kind: 'literal', value: '1' } }] })],
    ['mysql', draft('mysql', { columns: [textColumn('mysql', { nullable: false, default: { kind: 'null' } })] })],
    ['postgres', draft('postgres', { columns: [{ ...textColumn('postgres'), type: 'NUMERIC', length: null, precision: 10, scale: 2, default: { kind: 'literal', value: '12.345' } }] })],
    ['mysql', draft('mysql', { columns: [{ ...textColumn('mysql'), type: 'BIGINT', length: null, default: { kind: 'literal', value: '9223372036854775808' } }] })],
  ];
  for (const [provider, input] of invalid) expect(() => validateTableCreateInput(provider, input)).toThrow();
  expect(() => validateTableCreateInput('postgres', draft('postgres', { columns: [textColumn('postgres', { name: 'Label' }), textColumn('postgres', { id: 'different', name: 'label' })] }))).not.toThrow();
});

test('session-owned readonly plans enforce fresh target/permission, lock, expiry, one use and truthful native outcomes', async () => {
  const { driver, state } = fixture(), plans = new TableCreatePlans();
  const prepared = await plans.prepare(driver, 'postgres', 'lab', draft('postgres'), allowed);
  expect(state.writes).toEqual([]);
  await expect(plans.commit(driver, prepared.planId, () => { throw new Error('locked'); })).rejects.toThrow('locked');
  expect((await plans.commit(driver, prepared.planId, allowed)).outcome).toBe('created');
  await expect(plans.commit(driver, prepared.planId, allowed)).rejects.toThrow('失效');
  const exists = await plans.prepare(driver, 'postgres', 'lab', draft('postgres'), allowed); state.exists = true;
  expect((await plans.commit(driver, exists.planId, allowed)).outcome).toBe('rejected'); state.exists = false;
  const permission = await plans.prepare(driver, 'postgres', 'lab', draft('postgres'), allowed); state.permission = false;
  expect((await plans.commit(driver, permission.planId, allowed)).outcome).toBe('rejected'); state.permission = true;
  const schema = await plans.prepare(driver, 'postgres', 'lab', draft('postgres'), allowed); state.schemas = ['main'];
  expect((await plans.commit(driver, schema.planId, allowed)).outcome).toBe('rejected'); state.schemas = ['main', 'lab'];
  const wrong = await plans.prepare(driver, 'sqlite', 'main', draft('sqlite'), allowed);
  await expect(plans.commit(fixture().driver, wrong.planId, allowed)).rejects.toThrow('变化');
  const expired = await plans.prepare(driver, 'sqlite', 'main', draft('sqlite'), allowed);
  try { setSystemTime(new Date(expired.expiresAt + 1)); await expect(plans.commit(driver, expired.planId, allowed)).rejects.toThrow('失效'); }
  finally { setSystemTime(); }
  const closed = await plans.prepare(driver, 'sqlite', 'main', draft('sqlite'), allowed); plans.clear();
  await expect(plans.commit(driver, closed.planId, allowed)).rejects.toThrow('失效');
  expect(state.writes.length).toBe(1);
  const uncertain = await plans.prepare(driver, 'mysql', 'lab', draft('mysql'), allowed); state.after = () => { throw Object.assign(new Error('COMMIT response lost'), { code: 'ECONNRESET' }); };
  expect((await plans.commit(driver, uncertain.planId, allowed)).outcome).toBe('unknown'); state.after = null;
  const rejected = await plans.prepare(driver, 'sqlite', 'main', draft('sqlite'), allowed); state.fail = Object.assign(new Error('readonly file'), { code: 'ERR_SQLITE_ERROR', errcode: 8 });
  expect((await plans.commit(driver, rejected.planId, allowed)).outcome).toBe('rejected');
});

test('actual SQLite empty table has auto PK, unique constraint, quoted literal / binary defaults and rollback', () => {
  const db = new DatabaseSync(':memory:');
  const input = draft('sqlite', { table: 'quote"table', columns: [tableCreateNewColumn('sqlite', 'id', true), textColumn('sqlite', { nullable: false, unique: true, default: { kind: 'literal', value: "中文'\\path" } }), textColumn('sqlite', { id: 'binary', name: 'payload', type: 'BLOB', default: { kind: 'literal', value: '00ff' } })] });
  try {
    db.exec(buildTableCreateReview('sqlite', input).review.sql);
    const columns = db.prepare('PRAGMA table_info("quote""table")').all();
    expect(columns.length).toBe(3); expect(columns[0]?.pk).toBe(1);
    db.exec('INSERT INTO "quote""table" DEFAULT VALUES');
    const row = db.prepare('SELECT id, label, hex(payload) AS hex FROM "quote""table"').get();
    expect(row?.id).toBe(1); expect(row?.label).toBe("中文'\\path"); expect(row?.hex).toBe('00FF');
    expect(() => db.exec('INSERT INTO "quote""table" DEFAULT VALUES')).toThrow();
    db.exec('BEGIN'); db.exec(buildTableCreateReview('sqlite', draft('sqlite', { table: 'rollback' })).review.sql); db.exec('ROLLBACK');
    expect(db.prepare("SELECT name FROM sqlite_schema WHERE name='rollback'").all()).toEqual([]);
  } finally { db.close(); }
});

test('creation route bounds body and rejects missing confirmation or arbitrary SQL at commit', async () => {
  let commits = 0, prepares = 0;
  const app = new Hono().route('/', tableCreateRoutes({
    tableCreateOptions: async () => ({ provider: 'sqlite', database: 'main', schemas: ['main'], types: [], warnings: [] }),
    prepareTableCreate: async () => { prepares++; throw new Error('stop'); },
    commitTableCreate: async () => { commits++; throw new Error('stop'); },
    discardTableCreate: () => undefined,
  }));
  app.onError(error => new Response(error.message, { status: 400 }));
  const base = '/api/database/workspaces/w/relational/sessions/s/table-create';
  for (const value of [{ confirm: false }, { confirm: true, sql: 'DROP TABLE public.x' }, {}]) expect((await app.request(`${base}/plans/token/commit`, { method: 'POST', body: JSON.stringify(value) })).status).toBe(400);
  expect((await app.request(`${base}/plans`, { method: 'POST', body: 'x'.repeat(TABLE_CREATE_LIMITS.requestBytes + 1) })).status).toBe(400);
  expect((await app.request(`${base}/options?sql=CREATE`)).status).toBe(400);
  expect(commits).toBe(0); expect(prepares).toBe(0);
});
